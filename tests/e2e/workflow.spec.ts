import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { PDFDocument } from "pdf-lib";
import { test, expect, activate, accessible, signIn, createFamily } from "./helpers";

test("failed AI draft can be explicitly continued manually, reviewed and downloaded", async ({ page, local }, testInfo) => {
  const staff = await local.staff();
  await signIn(page, staff);
  const familyId = await createFamily(page);
  const context = "The family wants to agree a manageable next step before any provider contact.";
  await page.getByLabel("Family priorities and context", { exact: false }).fill(context);
  writeFileSync("tmp/e2e/provider-control.json", JSON.stringify({ failSchema: "lean_intervention_plan" }));
  try {
    await activate(page, page.getByRole("button", { name: "Draft action plan", exact: true }));
    await expect(page).toHaveURL(new RegExp(`/families/${familyId}/plan$`), { timeout: 45_000 });
    const manual = page.getByRole("button", { name: "Continue manually", exact: true });
    await expect(manual).toBeEnabled();
    await expect(page.getByRole("button", { name: "Mark plan reviewed", exact: true })).toHaveCount(0);
    const failed = (await local.db.query("select id,generation_state from public.plans where family_id=$1",[familyId])).rows[0];
    expect(failed.generation_state.status).toBe("failed");
    expect((await local.db.query("select count(*)::int n from public.plan_steps where plan_id=$1",[failed.id])).rows[0].n).toBe(0);
    await accessible(page);
    await activate(page, manual);
    await expect(page.getByText(/You chose to finish this draft manually/)).toBeVisible();
    await expect(page.getByRole("button", { name: "Mark plan reviewed", exact: true })).toHaveCount(0);
    const saved = (await local.db.query("select generation_source,generation_state from public.plans where id=$1",[failed.id])).rows[0];
    expect(saved.generation_source).toBe("manual");
    expect(saved.generation_state).toMatchObject({ status:"complete",pending_phase:null,completion_method:"manual",input_snapshot:failed.generation_state.input_snapshot });
    const add = page.locator("section").filter({ has: page.getByRole("heading", { name:"Add an action",exact:true }) });
    await add.getByLabel("Goal", { exact:true }).fill("Agree the next support priority");
    await add.getByLabel("Action", { exact:true }).fill("Discuss the family priority before provider contact");
    await add.getByLabel("Target date", { exact:true }).fill("2026-10-20");
    await add.getByLabel("Expected result", { exact:true }).fill("The family and case manager agree a safe next step.");
    await activate(page, add.getByRole("button", { name:"Add action",exact:true }));
    await expect(page.getByRole("button", { name:"Edit action",exact:true })).toHaveCount(1);
    await accessible(page);
    await activate(page, page.getByRole("button", { name:"Mark plan reviewed",exact:true }));
    await activate(page, page.getByRole("button", { name:"Confirm dates and mark reviewed",exact:true }));
    await activate(page, page.getByRole("main").getByRole("link", { name:"Review PDF",exact:true }));
    await expect(page.getByRole("button", { name:"Download PDF",exact:true })).toBeEnabled();
    const pendingDownload = page.waitForEvent("download");
    await activate(page, page.getByRole("button", { name:"Download PDF",exact:true }));
    const path = testInfo.outputPath("manually-prepared-plan.pdf");
    await (await pendingDownload).saveAs(path);
    const bytes = readFileSync(path);
    expect((await PDFDocument.load(bytes)).getPageCount()).toBeGreaterThan(0);
    const text = execFileSync("pdftotext", ["-","-"], { input:bytes,encoding:"utf8" }).replace(/\s+/g," ");
    expect(text).toContain("Discuss the family priority before provider contact");
    expect(text).toContain("The family and case manager agree a safe next step.");
    const audit = (await local.db.query("select action from public.activity_log where entity_id=$1",[failed.id])).rows.map(row=>row.action);
    expect(audit).toContain("plan.continued_manually");
    expect(audit).toContain("plan.reviewed");
    expect(audit).not.toContain("plan.generation_finished");
  } finally { writeFileSync("tmp/e2e/provider-control.json", "{}\n"); }
});

test("case intake through resumed generation, recovered edits, AI review, and the exact PDF download", async ({ page, context, local }, testInfo) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  const staff = await local.staff();
  await signIn(page, staff);
  const familyId = await createFamily(page);
  const familyContext = "The family wants a steady school routine. A relative helps twice a week. Calls should be after work; a previous application is awaiting a response.";
  await page.getByLabel("Family priorities and context", { exact: false }).fill(familyContext);
  await accessible(page);
  writeFileSync("tmp/e2e/provider-control.json", JSON.stringify({ delayMs: 600, failSchema: "lean_intervention_plan" }));
  await activate(page, page.getByRole("button", { name: "Draft action plan", exact: true }));
  await expect.poll(async () => (await local.db.query("select count(*)::int as n from public.plans where family_id=$1", [familyId])).rows[0].n).toBe(1);
  await page.reload();
  await page.goto(`/families/${familyId}/plan`);
  const otherTab = await context.newPage();
  await otherTab.goto(`/families/${familyId}/plan`);
  await expect(page.getByRole("button", { name: "Continue draft", exact: true })).toBeVisible({ timeout: 45_000 });
  const savedContext = await local.db.query("select f.summary, p.generation_state->'input_snapshot'->>'brief' as brief from public.families f join public.plans p on p.family_id=f.id where f.id=$1", [familyId]);
  expect(savedContext.rows[0].summary).toBe(familyContext);
  expect(JSON.parse(savedContext.rows[0].brief).summary).toBe(familyContext);
  const first = (await local.db.query("select p.id, count(s.id)::int as steps from public.plans p left join public.plan_steps s on s.plan_id=p.id where p.family_id=$1 group by p.id", [familyId])).rows;
  expect(first).toHaveLength(1);
  expect(first[0].steps).toBe(0);
  await otherTab.close();
  // Let every in-flight failed attempt settle before restoring the provider.
  await expect.poll(async () => (await local.db.query("select generation_state->>'status' as status from public.plans where id=$1", [first[0].id])).rows[0].status).toBe("failed");
  await page.reload();
  await expect(page.getByRole("button", { name: "Continue draft", exact: true })).toBeVisible();
  writeFileSync("tmp/e2e/provider-control.json", "{}\n");
  await activate(page, page.getByRole("button", { name: "Continue draft", exact: true }));
  await expect(page.getByRole("button", { name: "Edit action", exact: true })).toHaveCount(3, { timeout: 45_000 });
  expect((await local.db.query("select id from public.plans where family_id=$1", [familyId])).rows).toEqual([{ id: first[0].id }]);
  await expect(page.getByText(familyContext, { exact: true })).toBeVisible();
  await accessible(page);

  let article = page.locator("article[id^=step-]").first();
  await activate(page, article.getByRole("button", { name: "Edit action", exact: true }));
  await article.getByLabel("Action 1", { exact: true }).fill("Confirm the agreed preparation checklist");
  await accessible(page);
  page.once("dialog", dialog => dialog.accept());
  await page.reload();
  await activate(page, page.getByRole("button", { name: "Restore edit", exact: true }));
  article = page.locator("article[id^=step-]").first();
  await expect(article.getByLabel("Action 1", { exact: true })).toHaveValue("Confirm the agreed preparation checklist");
  await article.getByRole("combobox", { name: "Status", exact: true })
    .filter({ has: page.locator('option[value="waiting"]') }).selectOption("waiting");
  await article.getByRole("textbox", { name: "Why is this waiting?", exact: true }).fill("Waiting for the family's preferred review time.");
  await activate(page, article.getByRole("button", { name: "Save edits", exact: true }));
  await expect(article.getByRole("button", { name: "Edit action", exact: true })).toBeVisible();
  await page.reload();
  await expect(article).toContainText("Confirm the agreed preparation checklist");
  const nextStepId = await article.getAttribute("id");
  await page.goto("/families");
  const continueFamily = page.getByRole("link").filter({ hasText: "Continue plan" }).filter({ hasText: "Family 014" });
  await expect(continueFamily).toHaveAttribute("href", `/families/${familyId}/plan#${nextStepId}`);
  await activate(page, continueFamily);
  await expect(page).toHaveURL(new RegExp(`/families/${familyId}/plan#${nextStepId}$`));
  await expect(article).toBeInViewport();

  await activate(page, article.getByRole("button", { name: "Edit action", exact: true }));
  await activate(page, article.getByRole("button", { name: "Refine action", exact: true }));
  await article.getByLabel("AI revision instructions").fill("Clarify the goal title only. Keep the task, waiting status, date and progress note.");
  await activate(page, article.getByRole("button", { name: "Generate preview", exact: true }));
  await expect(article.getByRole("button", { name: "Apply to draft", exact: true })).toBeDisabled();
  await article.getByRole("checkbox", { name: /Title/ }).check();
  await activate(page, article.getByRole("button", { name: "Apply to draft", exact: true }));
  await expect(article.getByLabel("Action 1", { exact: true })).toHaveValue("Confirm the agreed preparation checklist");
  await expect(article.getByRole("textbox", { name: "Why is this waiting?", exact: true })).toHaveValue("Waiting for the family's preferred review time.");
  await activate(page, article.getByRole("button", { name: "Save edits", exact: true }));
  await expect(article.getByRole("button", { name: "Edit action", exact: true })).toBeVisible();

  const savedActions = async () => (await local.db.query("select a.* from public.plan_step_action_items a join public.plan_steps s on s.id=a.plan_step_id where s.plan_id=$1 order by a.id", [first[0].id])).rows;
  const beforeRefinement = await savedActions();
  await activate(page, page.getByRole("button", { name: "Refine plan with AI", exact: true }));
  const refinement = page.getByRole("dialog");
  await refinement.getByRole("textbox").fill("Clarify only the first goal title. Preserve all tasks, dates and progress notes.");
  await activate(page, refinement.getByRole("button", { name: "Generate preview", exact: true }));
  await expect(refinement.getByRole("button", { name: "Apply to working copy", exact: true })).toBeDisabled();
  await refinement.getByRole("checkbox", { name: /Title/ }).check();
  await accessible(page);
  await activate(page, refinement.getByRole("button", { name: "Apply to working copy", exact: true }));
  await activate(page, refinement.getByRole("button", { name: "Save to plan", exact: true }));
  await expect(refinement).toHaveCount(0);
  await expect(article.getByRole("button", { name: "Agree the housing support priorities", exact: true })).toBeVisible();
  expect(await savedActions()).toEqual(beforeRefinement);

  await activate(page, page.getByRole("button", { name: "Mark plan reviewed", exact: true }));
  await accessible(page);
  await activate(page, page.getByRole("alertdialog").getByRole("button", { name: "Cancel", exact: true }));
  await expect(page.getByRole("button", { name: "Mark plan reviewed", exact: true })).toBeFocused();
  await activate(page, page.getByRole("button", { name: "Mark plan reviewed", exact: true }));
  await activate(page, page.getByRole("button", { name: "Confirm dates and mark reviewed", exact: true }));
  // Observe the real preview blob without fetching it through a different CSP permission.
  const previewBlobs = await page.evaluateHandle(() => {
    const blobs = new Map<string, Blob>();
    const create = URL.createObjectURL.bind(URL);
    URL.createObjectURL = value => {
      const url = create(value);
      if (value instanceof Blob && value.type === "application/pdf") blobs.set(url, value);
      return url;
    };
    return blobs;
  });
  await activate(page, page.getByRole("main").getByRole("link", { name: "Review PDF", exact: true }));
  await expect(page.getByRole("button", { name: "Download PDF", exact: true })).toBeEnabled();
  await accessible(page);
  const preview = await page.locator("iframe[title$='reviewed plan PDF']").getAttribute("src");
  expect(preview).toMatch(/^blob:/);
  const previewBytes = await previewBlobs.evaluate(async (blobs, source) => Array.from(new Uint8Array(await blobs.get(source!.split("#")[0])!.arrayBuffer())), preview);
  await previewBlobs.dispose();
  const pendingDownload = page.waitForEvent("download");
  await activate(page, page.getByRole("button", { name: "Download PDF", exact: true }));
  const download = await pendingDownload;
  const path = testInfo.outputPath("reviewed-plan.pdf");
  await download.saveAs(path);
  const bytes = readFileSync(path);
  expect(createHash("sha256").update(bytes).digest("hex")).toBe(createHash("sha256").update(new Uint8Array(previewBytes)).digest("hex"));
  const pdf = await PDFDocument.load(bytes);
  expect(pdf.getPageCount()).toBeGreaterThan(0);
  expect(pdf.getTitle()).toBe("Family Support Intervention Plan");
  const reviewed = await local.db.query("select client_display from public.plans where id=$1", [first[0].id]);
  expect(reviewed.rows[0].client_display.reviewedAt).toBeTruthy();
  await page.screenshot({ path: testInfo.outputPath("reviewed-pdf.png"), fullPage: true });

  await page.getByRole("radio", { name: "Family takeaway", exact: true }).check();
  const prepareTakeaway = page.getByRole("button", { name: "Prepare family takeaway", exact: true });
  await expect(prepareTakeaway).toBeDisabled();
  await page.getByRole("checkbox", { name: /Confirm the agreed preparation checklist/ }).check();
  await expect(prepareTakeaway).toBeDisabled();
  await page.getByRole("checkbox", { name: /I discussed these selected steps and dates with the family/ }).check();
  await accessible(page);
  await activate(page, prepareTakeaway);
  await expect(page.getByRole("button", { name: "Download PDF", exact: true })).toBeEnabled();
  const familyDownload = page.waitForEvent("download");
  await activate(page, page.getByRole("button", { name: "Download PDF", exact: true }));
  const familyPath = testInfo.outputPath("family-takeaway.pdf");
  await (await familyDownload).saveAs(familyPath);
  const familyBytes = readFileSync(familyPath);
  const familyPdf = await PDFDocument.load(familyBytes);
  expect(familyPdf.getTitle()).toBe("Your next steps");
  const familyText = execFileSync("pdftotext", ["-", "-"], { input: familyBytes, encoding: "utf8" }).replace(/\s+/g, " ").trim();
  expect(familyText).toContain("Confirm the agreed preparation checklist");
  expect(familyText).not.toContain("Waiting for the family's preferred review time.");
  expect(familyText).not.toContain("Check the intake outcome");
  expect(familyText).not.toContain("Review ongoing arrangements");
  expect(familyText).not.toContain(familyContext);
  await page.setViewportSize({ width: 390, height: 844 });
  await accessible(page);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("family-takeaway-mobile.png"), fullPage: true });
  await page.getByRole("checkbox", { name: /Confirm the agreed preparation checklist/ }).uncheck();
  await expect(page.getByRole("button", { name: "Download PDF", exact: true })).toHaveCount(0);
  await expect(prepareTakeaway).toBeDisabled();
  await page.setViewportSize({ width: 1365, height: 900 });

  await page.goto(`/families/${familyId}/plan`);
  await activate(page, page.getByRole("button", { name: "Ask about this plan", exact: true }));
  await expect(page).toHaveURL(new RegExp(`/families/${familyId}/assistant$`));
  await page.getByRole("textbox", { name: "Message the assistant", exact: true }).fill("What should I confirm before a referral?");
  await activate(page, page.getByRole("button", { name: "Send", exact: true }));
  await expect(page.getByText("Review the latest saved task and confirm the family's preferred next step.", { exact: false })).toBeVisible();
  await accessible(page);
  expect(errors).toEqual([]);
});
